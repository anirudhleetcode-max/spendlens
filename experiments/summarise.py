"""Build experiments/reports/summary.md from every results/*/metrics.json (no hand-typed numbers).

    python -m experiments.summarise
"""
from __future__ import annotations

import json

from . import ROOT

RES = ROOT / "experiments" / "results"
OUT = ROOT / "experiments" / "reports" / "summary.md"


def pct(v):
    return "—" if v is None else f"{100 * v:.1f}%"


def f3(v):
    return "—" if v is None else f"{v:.3f}"


def main() -> None:
    runs = {p.parent.name: json.loads(p.read_text()) for p in sorted(RES.glob("*/metrics.json"))}
    env = {p.parent.name: json.loads(p.read_text()) for p in sorted(RES.glob("*/env.json"))}
    L = ["# Results summary", "",
         "Generated by `python -m experiments.summarise` from `experiments/results/*/metrics.json`.", ""]

    L += ["## Receipt field extraction (exact match)", "",
          "| run | data | variant | parser | n | merchant | date | total | total (norm.) | CER | word recall | s/receipt |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for rid, m in runs.items():
        if "variants" not in m:
            continue
        ds = m["dataset"]
        kind = "synthetic" if ds.get("synthetic") else "real"
        for vname, v in m["variants"].items():
            L.append(f"| {rid} | {ds['name']} ({kind}) | {vname} | {v.get('parser_version', '1.1')} | {v['n_receipts']} | "
                     f"{pct((v.get('merchant') or {}).get('exact'))} | {pct((v.get('date') or {}).get('exact'))} | "
                     f"{pct((v.get('total') or {}).get('exact'))} | {pct((v.get('total') or {}).get('normalised'))} | "
                     f"{f3((v.get('ocr') or {}).get('cer_mean'))} | {pct((v.get('ocr') or {}).get('word_recall_mean'))} | "
                     f"{v.get('ocr_seconds_mean')} |")
    L += ["", "## Is the total's confidence useful? (share flagged for review, accuracy of each group)", "",
          "| run | variant | flagged | accuracy if not flagged | accuracy if flagged |", "|---|---|---|---|---|"]
    for rid, m in runs.items():
        for vname, v in (m.get("variants") or {}).items():
            t = v.get("total")
            if t:
                L.append(f"| {rid} | {vname} | {pct(t['share_flagged'])} | {pct(t['accuracy_when_not_flagged'])} | "
                         f"{pct(t['accuracy_when_flagged'])} |")

    L += ["", "## Category classifier (synthetic data)", ""]
    for rid, m in runs.items():
        if "models" not in m:
            continue
        L += [f"### {rid}", "", f"Split: {m['dataset']['split']}; sizes {m['dataset']['sizes']}. "
              f"Selected: **{m['selected']}** ({m['selection']['rule']}).", "",
              "| model | val macro-F1 | test acc | test macro-F1 | test log-loss | test Brier | test ECE | merchant-only acc |",
              "|---|---|---|---|---|---|---|---|"]
        for name, r in m["models"].items():
            t = r["test"]
            L.append(f"| {name} | {f3(r['val']['macro_f1'])} | {pct(t['accuracy'])} | {f3(t['macro_f1'])} | "
                     f"{f3(t['log_loss'])} | {f3(t['brier'])} | {f3(t['ece'])} | "
                     f"{pct(t['by_input_kind'].get('merchant_only', {}).get('accuracy'))} |")
        c, a = m["calibration"], m["abstention"]
        L += ["", f"Temperature scaling: T = {c['temperature']}. Test ECE {c['test_before']['ece']} -> "
              f"{c['test_after']['ece']}, Brier {c['test_before']['brier']} -> {c['test_after']['brier']}, "
              f"log-loss {c['test_before']['log_loss']} -> {c['test_after']['log_loss']}.", "",
              f"Abstention: target {a['target_accuracy_on_val']} on validation -> threshold {a['threshold']} "
              f"(target reached on val: {a.get('target_reached_on_val', 'not recorded')}). On test: coverage "
              f"{pct(a['test_at_threshold']['coverage'])}, accuracy when suggesting "
              f"{pct(a['test_at_threshold']['accuracy_on_accepted'])}, accuracy of the abstained guesses "
              f"{pct(a['test_at_threshold']['accuracy_on_abstained'])}.", "",
              "Reliability (test, after calibration):", "", "| bin | n | mean confidence | accuracy |", "|---|---|---|---|"]
        L += [f"| {r['bin']} | {r['n']} | {f3(r['mean_confidence'])} | {f3(r['accuracy'])} |"
              for r in c["reliability_test_after"] if r["n"]]
        L += ["", "Top confusions: " + "; ".join(f"{x['true']} -> {x['predicted']} ({x['count']})"
                                                for x in m["top_confusions"][:5]), ""]

    L += ["## Run environments", "", "| run | when (UTC) | commit | dirty | tesseract | parser |", "|---|---|---|---|---|---|"]
    for rid, e in env.items():
        L.append(f"| {rid} | {e['timestamp']} | {e['git_commit']} | {e['git_dirty']} | {e.get('tesseract')} | "
                 f"{e.get('parser_version')} |")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
